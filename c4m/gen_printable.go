//go:build ignore

// gen_printable writes SafeName's printable table, pinned to one Unicode
// version so that a name's C4 ID never depends on which runtime encoded
// it. Run with a Go whose unicode package is that version:
//
//	go run gen_printable.go
//
// It writes testdata/safename-vector/printable-<version>.txt, the shared
// table every implementation embeds, and printable_table.go, Go's copy.
// A rune is printable when Go's unicode.IsPrint says so: a letter, mark,
// number, punctuation or symbol, or U+0020 SPACE.
package main

import (
	"bytes"
	"fmt"
	"os"
	"unicode"
)

const pinned = "17.0.0"

func main() {
	if unicode.Version != pinned {
		fmt.Fprintf(os.Stderr, "this Go has Unicode %s; the table is pinned to %s\n", unicode.Version, pinned)
		os.Exit(1)
	}
	type span struct{ lo, hi rune }
	var spans []span
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !unicode.IsPrint(r) {
			continue
		}
		if n := len(spans); n > 0 && spans[n-1].hi == r-1 {
			spans[n-1].hi = r
			continue
		}
		spans = append(spans, span{r, r})
	}

	var txt bytes.Buffer
	fmt.Fprintf(&txt, "# SafeName printable code points, Unicode %s: Go unicode.IsPrint\n", pinned)
	fmt.Fprintf(&txt, "# (letters, marks, numbers, punctuation, symbols, and U+0020).\n")
	fmt.Fprintf(&txt, "# One inclusive range per line, hex, LO..HI. Generated by c4m/gen_printable.go.\n")
	for _, s := range spans {
		fmt.Fprintf(&txt, "%04X..%04X\n", s.lo, s.hi)
	}
	if err := os.WriteFile("testdata/safename-vector/printable-"+pinned+".txt", txt.Bytes(), 0o644); err != nil {
		panic(err)
	}

	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by gen_printable.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&src, "package c4m\n\n")
	fmt.Fprintf(&src, "// printableUnicodeVersion is the Unicode version SafeName's printable\n")
	fmt.Fprintf(&src, "// test is pinned to (testdata/safename-vector/printable-%s.txt).\n", pinned)
	fmt.Fprintf(&src, "const printableUnicodeVersion = %q\n\n", pinned)
	fmt.Fprintf(&src, "// printableRanges holds the printable code points as inclusive ranges,\n")
	fmt.Fprintf(&src, "// sorted and disjoint.\n")
	fmt.Fprintf(&src, "var printableRanges = [...][2]rune{\n")
	for _, s := range spans {
		fmt.Fprintf(&src, "\t{0x%04X, 0x%04X},\n", s.lo, s.hi)
	}
	fmt.Fprintf(&src, "}\n")
	if err := os.WriteFile("printable_table.go", src.Bytes(), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("%d ranges\n", len(spans))
}
